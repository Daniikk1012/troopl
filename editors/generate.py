"""Generates the TrOOPL TextMate grammar and Sublime syntax from one source.

Run from anywhere: python editors/generate.py
Both outputs follow SPECIFICATION.pdf sections 1.7 (tokens) and 2.17
(grammar). Edit this file, not the generated ones.
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Section 1.7: whitespace is exactly [ \t\r\n]; identifiers run until
# whitespace, a bracket, '"' or '#'. Never use \s, \S or \b here.
IDENT = r'[^ \t\r\n()\[\]{}"#]'
TOKEN_END = r'(?![^ \t\r\n()\[\]{}"#])'
UPPER = r"\p{Lu}\p{Lt}"
VARIABLE = rf"[{UPPER}]{IDENT}*"
METHOD = rf'[^ \t\r\n()\[\]{{}}"#0-9{UPPER}]{IDENT}*'
# A method name made only of ASCII punctuation, such as + <> -> // , : .
OPERATOR = rf"[-+*/\\^=<>!&|%~.,:;@$?'`]+{TOKEN_END}"
NUMBER = rf"(?:0nan|0inf-?|[0-9]+(?:\.[0-9]*)?-?){TOKEN_END}"
INVALID_NUMBER = rf"[0-9]{IDENT}*"
VALUE_START = rf'[(\[{{"0-9{UPPER}]'

S = ".troopl"
COMMENT = "comment.line.number-sign" + S
STRING = "string.quoted.double" + S
ESCAPE = "constant.character.escape" + S
NUMERIC = "constant.numeric" + S
INVALID = "invalid.illegal.numeric" + S
ENVIRONMENT = "variable.language.environment" + S
VARIABLE_USE = "variable.other" + S
DEFINITION = "entity.name.variable" + S
PARAMETER = "variable.parameter" + S
METHOD_DEFINITION = "entity.name.function" + S
METHOD_CALL = "entity.name.function.call" + S
OPERATOR_CALL = "keyword.operator" + S
ENVIRONMENT_CALL = "support.function.environment" + S


def punctuation(kind, side):
    return f"punctuation.section.{kind}.{side}{S}"


# --- TextMate (VS Code, Shiki) -------------------------------------------
# TextMate regexes see one line at a time, so a definition whose value starts
# on the next line is shown as a plain variable, and an environment call is
# recognised only on the line of its opening bracket.


def bracket(name, open_, close, kind, patterns):
    return {
        "name": f"meta.{name}{S}",
        "begin": open_,
        "beginCaptures": {"0": {"name": punctuation(kind, "begin")}},
        "end": close,
        "endCaptures": {"0": {"name": punctuation(kind, "end")}},
        "patterns": patterns,
    }


def call_chain(begin, captures):
    return {
        "begin": begin,
        "beginCaptures": captures,
        "end": r"(?=[)\]])",
        "patterns": [{"include": "#chain"}],
    }


head = call_chain(
    rf"\G[ \t]*({METHOD})", {"1": {"name": ENVIRONMENT_CALL}}
)

textmate = {
    "$schema": "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
    "name": "TrOOPL",
    "scopeName": "source.troopl",
    "fileTypes": ["tr"],
    "comment": "Generated by editors/generate.py; do not edit.",
    "patterns": [
        call_chain(rf"\A[ \t]*({METHOD})", {"1": {"name": ENVIRONMENT_CALL}}),
        {"include": "#statements"},
    ],
    "repository": {
        "comment": {
            "match": "(#).*$",
            "name": COMMENT,
            "captures": {"1": {"name": "punctuation.definition.comment" + S}},
        },
        "string": {
            "name": STRING,
            "begin": '"',
            "beginCaptures": {
                "0": {"name": "punctuation.definition.string.begin" + S}
            },
            "end": '"(?!")',
            "endCaptures": {
                "0": {"name": "punctuation.definition.string.end" + S}
            },
            "patterns": [{"match": '""', "name": ESCAPE}],
        },
        "environment": {
            "match": r"(\()[ \t]*(\))",
            "name": ENVIRONMENT,
        },
        "paren": bracket(
            "group",
            r"\(",
            r"\)",
            "group",
            [head, {"include": "#statements"}],
        ),
        "block": bracket(
            "block",
            r"\[",
            r"\]",
            "brackets",
            [head, {"include": "#statements"}],
        ),
        "object": bracket(
            "object",
            r"\{",
            r"\}",
            "braces",
            [
                {"include": "#comment"},
                {"include": "#method-definition"},
                {"include": "#values"},
            ],
        ),
        # Inside {}: a method name, then every variable is a parameter until
        # the body, which is the next value.
        "method-definition": {
            "name": "meta.method" + S,
            "begin": f"({METHOD})",
            "beginCaptures": {"1": {"name": METHOD_DEFINITION}},
            "end": rf"(?=[^ \t\r\n#{UPPER}])",
            "patterns": [
                {"include": "#comment"},
                {"match": VARIABLE, "name": PARAMETER},
            ],
        },
        # Inside a file, () or []: definitions and values until the first
        # method, which starts the call chain that ends the statement list.
        "statements": {
            "patterns": [
                {"include": "#comment"},
                {
                    "match": f"({VARIABLE})[ \\t]+({VARIABLE})",
                    "captures": {
                        "1": {"name": DEFINITION},
                        "2": {"name": VARIABLE_USE},
                    },
                },
                {
                    "match": f"({VARIABLE})[ \\t]+({NUMBER})",
                    "captures": {
                        "1": {"name": DEFINITION},
                        "2": {"name": NUMERIC},
                    },
                },
                {
                    "match": f"({VARIABLE})(?=[ \\t]*[(\\[{{\"])",
                    "captures": {"1": {"name": DEFINITION}},
                },
                call_chain(
                    f"({OPERATOR})|({METHOD})",
                    {
                        "1": {"name": OPERATOR_CALL},
                        "2": {"name": METHOD_CALL},
                    },
                ),
                {"include": "#values"},
            ]
        },
        "chain": {
            "patterns": [
                {"include": "#comment"},
                {"match": OPERATOR, "name": OPERATOR_CALL},
                {"match": METHOD, "name": METHOD_CALL},
                {"include": "#values"},
            ]
        },
        "values": {
            "patterns": [
                {"include": "#comment"},
                {"include": "#environment"},
                {"include": "#paren"},
                {"include": "#block"},
                {"include": "#object"},
                {"include": "#string"},
                {"match": NUMBER, "name": NUMERIC},
                {"match": INVALID_NUMBER, "name": INVALID},
                {"match": VARIABLE, "name": VARIABLE_USE},
            ]
        },
    },
}

# --- Sublime syntax (Sublime Text, bat, Typst raw blocks) ----------------
# A context stack, so statement heads, call chains and parameter lists are
# tracked across lines. Only the definition check still needs its value to
# start on the same line.

NOT_SPACE = r"(?=[^ \t\r\n])"


def opening(kind, open_, contexts):
    return {
        "match": open_,
        "scope": punctuation(kind, "begin"),
        "push": contexts,
    }


def closing(kind, close):
    return {"match": close, "scope": punctuation(kind, "end"), "pop": True}


values = [
    {"include": "comments"},
    {"match": r"(\()[ \t]*(\))", "scope": ENVIRONMENT},
    opening("group", r"\(", ["group-body", "statement-head"]),
    opening("brackets", r"\[", ["block-body", "statement-head"]),
    opening("braces", r"\{", "object-body"),
    {
        "match": '"',
        "scope": "punctuation.definition.string.begin" + S,
        "push": "string-body",
    },
    {"match": "{{number}}", "scope": NUMERIC},
    {"match": "{{invalid_number}}", "scope": INVALID},
    {"match": "{{variable}}", "scope": VARIABLE_USE},
]


def single(rule):
    """The value rule, but leaving the context after one value."""
    rule = dict(rule)
    if "push" in rule:
        rule["set"] = rule.pop("push")
    elif "match" in rule:
        rule["pop"] = True
    return rule


sublime = {
    "name": "TrOOPL",
    "file_extensions": ["tr", "troopl"],
    "scope": "source.troopl",
    "variables": {
        "ident": IDENT,
        "variable": VARIABLE.replace(IDENT, "{{ident}}"),
        "method": METHOD.replace(IDENT, "{{ident}}"),
        "operator": OPERATOR,
        "number": NUMBER,
        "invalid_number": INVALID_NUMBER.replace(IDENT, "{{ident}}"),
        "value_start": VALUE_START,
    },
    "contexts": {
        "main": [
            {"match": r"(?=[\s\S])", "set": ["file-body", "statement-head"]},
        ],
        "file-body": [{"include": "statements"}],
        "comments": [
            {
                "match": "(#).*$",
                "scope": COMMENT,
                "captures": {"1": "punctuation.definition.comment" + S},
            }
        ],
        "string-body": [
            {"meta_include_prototype": False},
            {"meta_scope": STRING},
            {"match": '""', "scope": ESCAPE},
            {
                "match": '"',
                "scope": "punctuation.definition.string.end" + S,
                "pop": True,
            },
        ],
        "statement-head": [
            {"include": "comments"},
            {
                "match": "{{method}}",
                "scope": ENVIRONMENT_CALL,
                "set": "call-chain",
            },
            {"match": NOT_SPACE, "pop": True},
        ],
        "statements": [
            {"include": "comments"},
            {
                "match": r"({{variable}})(?=[ \t]*{{value_start}})",
                "captures": {"1": DEFINITION},
                "push": "definition-value",
            },
            {"match": "(?={{method}})", "push": "call-chain"},
            *values,
        ],
        "definition-value": [
            *[single(rule) for rule in values[1:]],
            {"match": NOT_SPACE, "pop": True},
        ],
        "call-chain": [
            {"match": r"(?=[)\]])", "pop": True},
            {"include": "comments"},
            {"match": "{{operator}}", "scope": OPERATOR_CALL},
            {"match": "{{method}}", "scope": METHOD_CALL},
            *values,
        ],
        "group-body": [
            {"meta_scope": "meta.group" + S},
            closing("group", r"\)"),
            {"include": "statements"},
        ],
        "block-body": [
            {"meta_scope": "meta.block" + S},
            closing("brackets", r"\]"),
            {"include": "statements"},
        ],
        "object-body": [
            {"meta_scope": "meta.object" + S},
            closing("braces", r"\}"),
            {"include": "comments"},
            {
                "match": "{{method}}",
                "scope": METHOD_DEFINITION,
                "push": "method-parameters",
            },
            *values,
        ],
        "method-parameters": [
            {"meta_scope": "meta.method" + S},
            {"include": "comments"},
            {"match": "{{variable}}", "scope": PARAMETER},
            {"match": NOT_SPACE, "pop": True},
        ],
    },
}


def yaml_scalar(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    return "'" + str(value).replace("'", "''") + "'"


def yaml(value, indent=0):
    pad = "  " * indent
    lines = []
    if isinstance(value, dict):
        for key, item in value.items():
            if isinstance(item, (dict, list)) and item:
                lines.append(f"{pad}{key}:")
                lines.extend(yaml(item, indent + 1))
            else:
                lines.append(f"{pad}{key}: {yaml_scalar(item)}")
    else:
        for item in value:
            if isinstance(item, dict):
                body = yaml(item, indent + 1)
                lines.append(f"{pad}- {body[0].lstrip()}")
                lines.extend(body[1:])
            elif isinstance(item, list):
                body = yaml(item, indent + 1)
                lines.append(f"{pad}- {body[0].lstrip()}")
                lines.extend(body[1:])
            else:
                lines.append(f"{pad}- {yaml_scalar(item)}")
    return lines


# --- Notepad++ User Defined Language (UDL 2.1) ---------------------------
# UDL has keyword lists, not contexts: it colours variables (words starting
# with an upper-case letter, as prefix keywords), the methods of the default
# environment (section 6.7), numbers, strings, comments and punctuation-only
# method names, and folds on brackets. Definitions, parameters and calls look
# alike, and UDL has one style for all brackets, so nesting depth cannot be
# coloured. Operators must stand between spaces, so '-' and '.' inside names
# such as then-else or utf-8 stay part of the name.

ENVIRONMENT_METHODS = (
    "io fs system utf-8 env eval box array true false core filename crash"
)
SPECIAL_NUMBERS = "0nan 0inf 0inf-"
OPERATORS = "+ - * / ^ = <> < > <= >= // -> , : . ; ! & | ~ ? % ** ++ == != <- =>"


def upper_case_letters():
    """Lu/Lt letters of Latin, Greek and Cyrillic: the variable prefixes."""
    import unicodedata

    blocks = list(range(0x41, 0x530)) + list(range(0x1E00, 0x1F00))
    return " ".join(
        chr(c) for c in blocks if unicodedata.category(chr(c)) in ("Lu", "Lt")
    )


UDL_PALETTES = {
    # name: (suffix, dark mode, colours)
    "light": (
        "",
        False,
        {
            # Seven separate hues; method names stay black.
            "default": "000000",
            "background": "FFFFFF",
            "comment": "8A8A8A",
            "number": "2E7D32",
            "variable": "1F5FD0",
            "environment": "9C27B0",
            "operator": "E65100",
            "bracket": "00838F",
            "string": "C62828",
        },
    ),
    "dark": (
        " (dark mode)",
        True,
        {
            "default": "D4D4D4",
            "background": "1E1E1E",
            "comment": "7F848E",
            "number": "98C379",
            "variable": "82AAFF",
            "environment": "DA70D6",
            "operator": "FFA040",
            "bracket": "4EC9B0",
            "string": "E06C75",
        },
    ),
}


def udl(palette):
    from xml.sax.saxutils import escape, quoteattr

    suffix, dark, colour = UDL_PALETTES[palette]
    keywords = {
        "Comments": "00# 01 02((EOL)) 03 04",
        "Numbers, prefix1": "",
        "Numbers, prefix2": "",
        "Numbers, extras1": ".",
        "Numbers, extras2": "",
        "Numbers, suffix1": "-",
        "Numbers, suffix2": "",
        "Numbers, range": "",
        "Operators1": "",
        "Operators2": OPERATORS,
        # Code-1 folders are matched wherever they appear and end the word
        # before them; code-2 folders must be whole words between spaces,
        # which would miss the brackets in (io print X).
        "Folders in code1, open": "( [ {",
        "Folders in code1, middle": "",
        "Folders in code1, close": ") ] }",
        "Folders in code2, open": "",
        "Folders in code2, middle": "",
        "Folders in code2, close": "",
        "Folders in comment, open": "",
        "Folders in comment, middle": "",
        "Folders in comment, close": "",
        "Keywords1": upper_case_letters(),
        "Keywords2": ENVIRONMENT_METHODS,
        "Keywords3": SPECIAL_NUMBERS,
        **{f"Keywords{i}": "" for i in range(4, 9)},
        "Delimiters": '00" 01 02" '
        + " ".join(f"{i:02}" for i in range(3, 24)),
    }
    # style name: (colour key or None for the default, font style)
    # font style: 0 normal, 1 bold, 2 italic, 3 bold italic
    styles = {
        "DEFAULT": (None, 0),
        "COMMENTS": ("comment", 2),
        "LINE COMMENTS": ("comment", 2),
        "NUMBERS": ("number", 0),
        "KEYWORDS1": ("variable", 0),
        "KEYWORDS2": ("environment", 1),
        "KEYWORDS3": ("number", 0),
        **{f"KEYWORDS{i}": (None, 0) for i in range(4, 9)},
        "OPERATORS": ("operator", 1),
        "FOLDER IN CODE1": ("bracket", 1),
        "FOLDER IN CODE2": (None, 0),
        "FOLDER IN COMMENT": (None, 0),
        "DELIMITERS1": ("string", 0),
        **{f"DELIMITERS{i}": (None, 0) for i in range(2, 9)},
    }
    lines = [
        '<?xml version="1.0" encoding="UTF-8" ?>',
        "<!-- Generated by editors/generate.py; do not edit. -->",
        "<NotepadPlus>",
        f'    <UserLang name={quoteattr("TrOOPL" + suffix)} ext="tr"'
        f' darkModeTheme="{"yes" if dark else "no"}" udlVersion="2.1">',
        "        <Settings>",
        '            <Global caseIgnored="no" allowFoldOfComments="no"'
        ' foldCompact="no" forcePureLC="0" decimalSeparator="0" />',
        '            <Prefix Keywords1="yes" Keywords2="no" Keywords3="no"'
        ' Keywords4="no" Keywords5="no" Keywords6="no" Keywords7="no"'
        ' Keywords8="no" />',
        "        </Settings>",
        "        <KeywordLists>",
    ]
    for name, words in keywords.items():
        lines.append(
            f"            <Keywords name={quoteattr(name)}>{escape(words)}</Keywords>"
        )
    lines += ["        </KeywordLists>", "        <Styles>"]
    for name, (key, font) in styles.items():
        fg = colour[key] if key else colour["default"]
        lines.append(
            f'            <WordsStyle name="{name}" fgColor="{fg}"'
            f' bgColor="{colour["background"]}" colorStyle="{1 if key else 0}"'
            f' fontName="" fontStyle="{font}" nesting="0" />'
        )
    lines += ["        </Styles>", "    </UserLang>", "</NotepadPlus>"]
    return "\n".join(lines) + "\n"


def main():
    notepad = HERE / "notepad++"
    notepad.mkdir(exist_ok=True)
    (notepad / "TrOOPL.udl.xml").write_text(
        udl("light"), encoding="utf-8", newline="\r\n"
    )
    (notepad / "TrOOPL_DM.udl.xml").write_text(
        udl("dark"), encoding="utf-8", newline="\r\n"
    )
    vscode = HERE / "vscode" / "syntaxes" / "troopl.tmLanguage.json"
    vscode.parent.mkdir(parents=True, exist_ok=True)
    vscode.write_text(
        json.dumps(textmate, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    header = [
        "%YAML 1.2",
        "---",
        "# Generated by editors/generate.py; do not edit.",
        "# https://www.sublimetext.com/docs/syntax.html",
    ]
    (HERE / "sublime" / "TrOOPL.sublime-syntax").parent.mkdir(exist_ok=True)
    (HERE / "sublime" / "TrOOPL.sublime-syntax").write_text(
        "\n".join(header + yaml(sublime)) + "\n", encoding="utf-8", newline="\n"
    )


if __name__ == "__main__":
    main()
